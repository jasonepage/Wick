//  The bulk is ported 1:1 from Hunch/Engine/Loc.swift (235 vetted keys). The WEB-only
//  keys (stats, the Reveal, settings/reminder, suggested questions, a few labels) have
//  AI-DRAFTED es/fr/it/de values that need a fluent skim before release. Placeholders:
//  %@ (string), %d (number), filled in order by t(key, ...args).
//  The zh (Simplified Chinese) table is web only and AI drafted; it needs a native
//  speaker's skim. Menus follow it, but the game itself is still played in English.
//

export type Lang = "en" | "es" | "fr" | "it" | "de" | "zh";
export const LANGS: Lang[] = ["en", "es", "fr", "it", "de", "zh"];
export const LANG_LABEL: Record<Lang, string> = { en: "English", es: "Español", fr: "Français", it: "Italiano", de: "Deutsch", zh: "中文" };
function isLang(s: unknown): s is Lang { return s === "en" || s === "es" || s === "fr" || s === "it" || s === "de" || s === "zh"; }
let current: Lang = resolveLang();
function resolveLang(): Lang {
  try { const s = localStorage.getItem("wick.lang"); if (isLang(s)) return s; } catch { /* off */ }
  const n = (navigator.language || "en").slice(0, 2).toLowerCase();
  return isLang(n) ? n : "en";
}
export function getLang(): Lang { return current; }
export function setLang(l: Lang): void { current = l; try { localStorage.setItem("wick.lang", l); } catch { /* ignore */ } }
export function t(key: string, ...args: Array<string | number>): string {
  const tpl = TABLES[current][key] ?? TABLES.en[key] ?? key;
  let i = 0;
  return tpl.replace(/%@|%d/g, () => String(args[i++] ?? ""));
}
