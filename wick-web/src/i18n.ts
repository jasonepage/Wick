export type Lang = "en" | "es" | "fr" | "it" | "de";
export const LANGS: Lang[] = ["en", "es", "fr", "it", "de"];
export const LANG_LABEL: Record<Lang, string> = { en: "English", es: "Español", fr: "Français", it: "Italiano", de: "Deutsch" };
function isLang(s: unknown): s is Lang { return s === "en" || s === "es" || s === "fr" || s === "it" || s === "de"; }
let current: Lang = resolveLang();
function resolveLang(): Lang {
  try { const s = localStorage.getItem("wick.lang"); if (isLang(s)) return s; } catch { /* off */ }
  const n = (navigator.language || "en").slice(0, 2).toLowerCase();
  return isLang(n) ? n : "en";
}
export function getLang(): Lang { return current; }
export function setLang(l: Lang): void { current = l; try { localStorage.setItem("wick.lang", l); } catch { /* ignore */ } }
export function t(key: string, ...args: Array<string | number>): string {
  const tpl = TABLES[current][key] ?? TABLES.en[key] ?? key;
  let i = 0;
  return tpl.replace(/%@|%d/g, () => String(args[i++] ?? ""));
}
